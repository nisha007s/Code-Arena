// Generates supabase/migrations/20261114000002_seed_problems.sql from problem-bank/ (read-only).
// Public fields only: hidden tests and reference solutions are never written to the database.
// The 7 problems whose hidden tests were resized for the WebAssembly judge get matching
// constraints, and language notes mention only the two Supabase languages (Python, JavaScript).
//
//   node scripts/supabase/build-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { starterFor } from '../../server/starters.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const limits = JSON.parse(fs.readFileSync(path.join(root, 'supabase', 'judge-limits.json'), 'utf8'));

// Exact text replacements per problem (the original problem.json files stay unchanged).
export const CONSTRAINT_EDITS = {
  'target-pair': [
    ['2 ≤ n ≤ 200000', '2 ≤ n ≤ 40000'],
    ['Use a 64-bit type (long in Java/C#, long long in C++) for sums or differences.', 'Python integers and JavaScript numbers represent it exactly.'],
  ],
  'first-occurrence': [['1 ≤ n ≤ 200000', '1 ≤ n ≤ 100000']],
  'longest-streak': [['1 ≤ n ≤ 200000', '1 ≤ n ≤ 150000']],
  'maximum-segment-sum': [
    ['1 ≤ n ≤ 200000', '1 ≤ n ≤ 80000'],
    ['The answer can be as large as 2·10^14. Use a 64-bit integer type (long in Java/C#, long long in C++).', 'The answer can be as large as 8·10^13. Python integers and JavaScript numbers (exact up to 2^53) represent it exactly.'],
  ],
  'merge-maintenance-slots': [
    ['1 ≤ n ≤ 100000', '1 ≤ n ≤ 25000'],
    ['The output can contain up to 100001 lines, so build it efficiently (for example with a string builder)', 'The output can contain up to 25001 lines, so build it efficiently (for example by joining strings)'],
  ],
  'next-warmer-day': [
    ['1 ≤ n ≤ 200000', '1 ≤ n ≤ 80000'],
    ['The output has up to 200000 numbers;', 'The output has up to 80000 numbers;'],
  ],
  'cheapest-route': [
    ['1 ≤ n ≤ 100000', '1 ≤ n ≤ 20000'],
    ['0 ≤ m ≤ 200000', '0 ≤ m ≤ 40000'],
    ['A route cost can reach about 10^14. Use a 64-bit integer type (long in Java/C#, long long in C++).', 'A route cost can reach about 2·10^13. Python integers and JavaScript numbers (exact up to 2^53) represent it exactly.'],
  ],
};

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const j = (v) => q(JSON.stringify(v)) + '::jsonb';
const rows = [];
const changes = [];
for (const dir of fs.readdirSync(path.join(root, 'problem-bank', 'problems')).sort()) {
  const p = JSON.parse(fs.readFileSync(path.join(root, 'problem-bank', 'problems', dir, 'problem.json'), 'utf8'));
  let constraints = [...p.constraints];
  for (const [from, to] of CONSTRAINT_EDITS[p.id] || []) {
    const i = constraints.findIndex((c) => c.includes(from));
    if (i < 0) throw new Error(`${p.id}: constraint text not found: ${from}`);
    constraints[i] = constraints[i].replace(from, to);
    changes.push(`${p.id}: "${from}" -> "${to}"`);
  }
  const all = JSON.stringify([constraints, p.statement, p.inputFormat, p.outputFormat]);
  if (/\bJava\b|C\+\+|C#/.test(all)) throw new Error(`${p.id}: text still mentions a language Supabase does not run`);
  const lim = limits[dir];
  if (!lim) throw new Error(`no calibrated limits for ${dir}`);
  rows.push(`(${q(p.id)}, ${p.number}, ${q(p.title)}, ${q(p.difficulty)}, array[${p.tags.map(q).join(', ')}]::text[], ${q(p.primaryTopic)},
  ${j(p.statement)}, ${j(p.inputFormat)}, ${j(p.outputFormat)}, ${j(constraints)},
  ${j(p.examples.map((e) => ({ input: e.input, output: e.output, explanation: e.explanation || '' })))},
  ${j({ python: starterFor(p, 'python'), javascript: starterFor(p, 'javascript') })}, ${j(lim)})`);
}
const sql = `-- Generated by scripts/supabase/build-seed.mjs — do not edit by hand.
-- Public problem data only (statements, examples, starters, limits). Hidden tests are not stored here.
insert into public.problems (id, number, title, difficulty, tags, primary_topic, statement, input_format, output_format, constraints, examples, starters, time_limits) values
${rows.join(',\n')}
on conflict (id) do update set number = excluded.number, title = excluded.title, difficulty = excluded.difficulty, tags = excluded.tags,
  primary_topic = excluded.primary_topic, statement = excluded.statement, input_format = excluded.input_format, output_format = excluded.output_format,
  constraints = excluded.constraints, examples = excluded.examples, starters = excluded.starters, time_limits = excluded.time_limits;
`;
fs.writeFileSync(path.join(root, 'supabase', 'migrations', '20261114000002_seed_problems.sql'), sql);
console.log(`seed written: ${rows.length} problems; ${changes.length} constraint edits:\n  ` + changes.join('\n  '));
